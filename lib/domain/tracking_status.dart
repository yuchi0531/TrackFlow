/// 配送ステータスに関するドメイン判定ロジック。
///
/// 各社のステータス表現は異なるため、配送状況の意味づけ（配達完了かどうかなど）を
/// 一箇所に集約し、一覧の絞り込み・自動アーカイブ・バックグラウンド通知・カード表示で
/// 同じ判定を共有する。Presentation / Data どちらの層からも参照できるよう domain に置く。
library;

/// 配達完了とみなしてはいけない表現（部分一致の誤検知を打ち消す）。
///
/// 例: エスポ便の `一部配達完了`（122）は「一部だけ配達済みで残りは配送中」、
/// `配達完了 返還完了`（230）は「配達後に差出人へ返還された」状態。
/// どちらも追跡を終えてよい状態ではないため、配達完了の対象から除外する。
/// 除外しないと自動更新が止まり、残りの荷物の追跡が行われなくなる。
const _notDeliveredKeywords = [
  '一部配達完了',
  '返還完了',
];

/// ステータス文字列が配達完了を示すかどうかを判定する。
///
/// 各社の配達完了表現を網羅する:
/// - ヤマト・佐川: `配達完了`
/// - 日本郵便: `お届け済み` / `投函完了`
/// - 佐川: `配達済み` / `お届け完了`
/// - エスポ便: `引渡完了`（`配達完了【宅配BOX】` 等は `配達完了` で拾える）
///
/// `返品完了` のように「完了」でも配達完了ではない表現を誤検知しないよう、
/// `完了` だけでの判定はしない。また [_notDeliveredKeywords] に該当する
/// 表現（`一部配達完了` / `返還完了`）は、部分一致で拾われても除外する。
bool isDeliveredStatus(String status) {
  if (_notDeliveredKeywords.any(status.contains)) return false;

  const deliveredKeywords = [
    '配達完了', // ヤマト・佐川・エスポ便
    'お届け済み', // 日本郵便
    '投函完了', // 日本郵便（ポスト投函）
    '配達済み', // 佐川
    'お届け完了', // 佐川
    '引渡完了', // エスポ便（115: 引渡完了【受取先変更】）
  ];
  return deliveredKeywords.any(status.contains);
}

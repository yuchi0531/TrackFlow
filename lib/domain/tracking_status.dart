/// 配送ステータスに関するドメイン判定ロジック。
///
/// 各社のステータス表現は異なるため、配送状況の意味づけ（配達完了かどうかなど）を
/// 一箇所に集約し、一覧の絞り込み・自動アーカイブ・バックグラウンド通知・カード表示で
/// 同じ判定を共有する。Presentation / Data どちらの層からも参照できるよう domain に置く。
library;

/// ステータス文字列が配達完了を示すかどうかを判定する。
///
/// 各社の配達完了表現を網羅する:
/// - ヤマト・佐川: `配達完了`
/// - 日本郵便: `お届け済み` / `投函完了`
/// - 佐川: `配達済み` / `お届け完了`
bool isDeliveredStatus(String status) {
  const deliveredKeywords = [
    '配達完了', // ヤマト・佐川
    'お届け済み', // 日本郵便
    '投函完了', // 日本郵便（ポスト投函）
    '配達済み', // 佐川
    'お届け完了', // 佐川
  ];
  return deliveredKeywords.any(status.contains);
}
